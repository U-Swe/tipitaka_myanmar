  /// subtitle (ခေါင်းစဉ်) နဲ့ title တူရင် အဲဒီ PDF ဖိုင်နာမည်ကို ပြန်ပေးသည်။
  static String? fileNameForSubtitle(String pitakaTitle, String subtitle) {
    final books = allPitakaMap[pitakaTitle];
    if (books == null) return null;

    final key = _normalize(subtitle);
    for (final book in books) {
      final title = book['title'];
      final fileName = book['fileName'];
      if (title != null && fileName != null && _normalize(title) == key) {
        return fileName;
      }
    }
    return null;
  }

  static String _normalize(String value) {
    return value.replaceAll(RegExp(r'\s+'), ' ').trim();
  }
